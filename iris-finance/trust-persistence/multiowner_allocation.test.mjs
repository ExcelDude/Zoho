import assert from 'node:assert/strict';
import {prepareMultiOwnerReceipt} from './multiowner_allocation.mjs';
let n=0;const expect=(a,b)=>{assert.deepEqual(a,b);n++};
const receipt={bankTransactionId:'bank-1',booksEvidenceId:'books-1',bankEvidenceId:'rbc-1',leaseId:'L1',tenantId:'T1',propertyId:'P1',pool:'RENT',status:'CLEARED',bankVerified:true,booksVerified:true,bankMappingApproved:true,tenantLeaseIdentityVerified:true,ownershipApproved:true,booksBankAccountId:'rent-id',amountCents:10001,clearedAt:'2026-11-21'};
const own=[{ownerId:'A',propertyId:'P1',ownershipSnapshotId:'S1',basisPoints:6000,verified:true},{ownerId:'B',propertyId:'P1',ownershipSnapshotId:'S1',basisPoints:4000,verified:true}];
const run=(r=receipt,o=own)=>prepareMultiOwnerReceipt({receipt:r,ownership:o,approvedBankAccountId:'rent-id'});
const good=run();expect(good.status,'MULTI_OWNER_PREVIEW_READY');expect(good.allocations.map(x=>x.amountCents),[6001,4000]);expect(good.unallocatedCents,0);expect(good.postingAllowed,false);
expect(run({...receipt,amountCents:5000}).allocations.map(x=>x.amountCents),[3000,2000]);
expect(run({...receipt,amountCents:1}).allocations.map(x=>x.amountCents),[1]);
const thirds=own.map((o,i)=>({...o,ownerId:String.fromCharCode(65+i),basisPoints:i===0?3334:3333})).concat([{...own[1],ownerId:'C',basisPoints:3333}]).slice(0,3);
expect(run({...receipt,amountCents:100},thirds).status,'MULTI_OWNER_PREVIEW_READY');
expect(run({...receipt,amountCents:100},thirds).allocations.reduce((s,x)=>s+x.amountCents,0),100);
expect(run(receipt,[...own].reverse()).allocationFingerprint,good.allocationFingerprint);
expect(run({...receipt,amountCents:10002}).trust.eventKey,good.trust.eventKey);
expect(run({...receipt,status:'PENDING'}).status,'HOLD');
expect(run({...receipt,pool:'DEPOSIT'}).status,'HOLD');
expect(run({...receipt,bankMappingApproved:false}).status,'HOLD');
expect(run({...receipt,tenantLeaseIdentityVerified:false}).status,'HOLD');
expect(run({...receipt,bankVerified:false}).status,'HOLD');
expect(run({...receipt,booksVerified:false}).status,'HOLD');
expect(run({...receipt,ownershipApproved:false}).status,'HOLD');
expect(run({...receipt,amountCents:0}).status,'HOLD');
expect(run({...receipt,amountCents:1.4}).status,'HOLD');
expect(run(receipt,[{...own[0],basisPoints:5000},own[1]]).status,'HOLD');
expect(run(receipt,[own[0],own[0]]).status,'HOLD');
expect(run(receipt,[own[0],{...own[1],ownershipSnapshotId:'S2'}]).status,'HOLD');
expect(run(receipt,[own[0],{...own[1],propertyId:'P2'}]).status,'HOLD');
expect(run(receipt,[own[0],{...own[1],verified:false}]).status,'HOLD');
expect(run(receipt,[]).status,'HOLD');
console.log('Multi-owner allocation assertions passed: '+n);
