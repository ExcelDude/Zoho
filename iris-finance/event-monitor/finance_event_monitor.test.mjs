import {FinanceEventMonitor} from "./finance_event_monitor.mjs";
import assert from "node:assert/strict";
const h="a".repeat(64), e={org_id:"IRIS_TEST",event_kind:"RENT_CHARGE",source_system:"iris-pms",source_event_id:"LEASE-1/2027-01",accounting_period:"2027-01",payload_sha256:h,amount_cents:300000};
const m=new FinanceEventMonitor({maxAttempts:2,baseRetryMs:100}),k=m.key(e);
assert.equal(m.enqueue(e,1000).status,"PENDING");
assert.equal(m.enqueue(e,1000).replayed,true);
assert.equal(m.enqueue({...e,payload_sha256:"b".repeat(64)},1000).conflict,true);
assert.equal(m.begin(k,1000).attempts,1);
assert.equal(m.failed(k,{category:"TRANSIENT_PRE_SUBMIT",code:"HTTP_503"},1100).status,"RETRY_WAIT");
assert.throws(()=>m.begin(k,1150),/Backoff active/);
assert.equal(m.begin(k,1200).attempts,2);
assert.equal(m.failed(k,{category:"TRANSIENT_PRE_SUBMIT",code:"TIMEOUT_PRE_SUBMIT"},1300).status,"DEAD_LETTER");
const f={...e,source_event_id:"LEASE-2/2027-01"},fk=m.key(f);
m.enqueue(f,2000);m.begin(fk,2000);assert.equal(m.failed(fk,{category:"UNCERTAIN_AFTER_SUBMIT",code:"TIMEOUT"},2100).status,"UNCERTAIN");
assert.throws(()=>m.begin(fk,2200),/Cannot dispatch/);
assert.throws(()=>m.reconcileUncertain(fk,{},2300),/Require existing/);
assert.equal(m.reconcileUncertain(fk,{foundBooksId:"BOOKS-123"},2400).status,"SUCCEEDED");
const g={...e,source_event_id:"LEASE-3/2027-01"},gk=m.key(g);
m.enqueue(g,3000);m.begin(gk,3000);assert.equal(m.failed(gk,{category:"PERMANENT_VALIDATION",code:"INVALID_OWNER"},3100).status,"BLOCKED");
const j={...e,source_event_id:"LEASE-4/2027-01"},jk=m.key(j);
m.enqueue(j,4000);m.begin(jk,4000);m.failed(jk,{category:"UNCERTAIN_AFTER_SUBMIT",code:"TIMEOUT"},4100);
assert.equal(m.reconcileUncertain(jk,{definitiveNoPost:true,approvedBy:"REVIEWER"},4200).status,"RETRY_WAIT");
assert.equal(m.begin(jk,4200).attempts,2);assert.equal(m.succeeded(jk,"BOOKS-456",4300).status,"SUCCEEDED");
assert.deepEqual(m.snapshot(),{total:4,pending:0,in_flight:0,retry_wait:0,succeeded:2,uncertain:0,blocked:1,dead_letter:1});
console.log("Event monitor tests passed");
