-- Schema sketch for a future durable Iris integration database. NOT DEPLOYED.
-- A production service must use a transactional SQL adapter with these invariants.
CREATE TABLE IF NOT EXISTS iris_finance_events (
 event_key TEXT PRIMARY KEY,
 source_system TEXT NOT NULL,
 source_id TEXT NOT NULL,
 source_version TEXT NOT NULL,
 event_type TEXT NOT NULL,
 organization_id TEXT NOT NULL,
 occurred_at TIMESTAMPTZ NOT NULL,
 payload_hash TEXT NOT NULL,
 payload_json JSONB NOT NULL,
 status TEXT NOT NULL DEFAULT 'RECEIVED'
   CHECK(status IN ('RECEIVED','PROCESSING','PREVIEW_READY','HOLD','QUARANTINED')),
 claim_token UUID,
 claimed_at TIMESTAMPTZ,
 result_json JSONB,
 attempts INTEGER NOT NULL DEFAULT 0,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS iris_finance_event_audit (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 event_key TEXT NOT NULL REFERENCES iris_finance_events(event_key),
 action TEXT NOT NULL,
 reason_code TEXT,
 actor_id TEXT NOT NULL,
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 details JSONB NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX IF NOT EXISTS idx_iris_finance_events_status ON iris_finance_events(status,created_at);
-- Required adapter semantics:
-- insertOrGet: INSERT ... ON CONFLICT DO NOTHING, then SELECT and compare payload_hash.
-- claim: one atomic UPDATE ... WHERE status='RECEIVED' RETURNING ...;
-- token must be generated by database, never trusted from caller.
-- complete: UPDATE ... WHERE event_key=? AND status='PROCESSING' AND claim_token=?;
-- if update count != 1, throw; never acknowledge a lost claim.
-- quarantine: status=QUARANTINED plus immutable audit row.
-- retries: only RECEIVED events that provably made NO external write;
-- uncertain external writes stay QUARANTINED until verified by reference + readback.
-- restrict DB roles; do not expose this table to client/browser or service anon keys.
