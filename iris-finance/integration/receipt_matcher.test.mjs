import assert from 'node:assert/strict';
import {assessReceiptBatch,buildReceiptExceptionQueue} from './receipt_matcher.mjs';
const bankAccounts=[{booksAccountId:'B1',pool:'RENT_TRUST',approved:true},{booksAccountId:'B2',pool:'DEPOSIT_TRUST',approved:true},{booksAccountId:'B3',pool:'OPERATING',approved:true}];
const leaseCandidates=[{leaseId:'L1',tenantId:'T1',propertyId:'P1',period:'2027-01',expectedRentCents:300000}];
const tenantMappings=[{tenantId:'T1',booksCustomerId:'C1',independentlyVerified:true}];
const verifiedReference={verified:true,verificationMethod:'INDEPENDENT_ACCOUNT_MAPPING',tenantId:'T1',leaseId:'L1',propertyId:'P1',booksCustomerId:'C1'};
const receipt={booksTransactionId:'TX1',booksBankAccountId:'B1',amountCents:300000,clearedAt:'2027-01-03',settlementStatus:'CLEARED',booksEvidenceId:'BK1',bankStatementEvidenceId:'BANK1',sourceSystem:'BOOKS_BANK',verifiedReference};
const base={bankAccounts,leaseCandidates,tenantMappings};
const run=(r,options={})=>assessReceiptBatch({...base,receipts:[r],...options});
let x=run(receipt);assert.equal(x.candidates,1);assert.equal(x.rows[0].classification,'RENT_CANDIDATE');assert.equal(x.postingsCreated,0);
assert.equal(run({...receipt,booksBankAccountId:'UNKNOWN'}).reviewRequired,1);
assert.equal(run({...receipt,verifiedReference:null}).reviewRequired,1);
assert.equal(run({...receipt,amountCents:250000}).reviewRequired,1);
assert.equal(run({...receipt,settlementStatus:'PENDING'}).reviewRequired,1);
assert.equal(run({...receipt,bankStatementEvidenceId:null}).reviewRequired,1);
assert.equal(run(receipt,{appliedReceiptIds:['TX1']}).reviewRequired,1);
assert.equal(assessReceiptBatch({...base,receipts:[receipt,receipt]}).reviewRequired,1);
assert.equal(run({...receipt,booksBankAccountId:'B3'}).reviewRequired,1);
const deposit={...receipt,booksBankAccountId:'B2',amountCents:150000,verifiedReference:{...verifiedReference,depositType:'SECURITY',expectedDepositCents:150000}};
assert.equal(run(deposit).rows[0].classification,'DEPOSIT_CANDIDATE');
assert.equal(run({...deposit,verifiedReference:{...verifiedReference}}).reviewRequired,1);
assert.equal(run({...receipt,verifiedReference:{...verifiedReference,verificationMethod:'NAME_MATCH'}}).reviewRequired,1);
assert.equal(run({...receipt,verifiedReference:{...verifiedReference,booksCustomerId:'OTHER'}}).reviewRequired,1);
assert.equal(buildReceiptExceptionQueue(run({...receipt,booksBankAccountId:'UNKNOWN'}))[0].autoRetry,false);
assert.throws(()=>run(receipt,{bankAccounts:[bankAccounts[0],bankAccounts[0]]}),/DUPLICATE_OR_INVALID_BANK_ACCOUNT/);
console.log('15 receipt-matching safety assertions passed. No Zoho Books writes.');
